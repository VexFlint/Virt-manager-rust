//! VM cloning — upstream's `cloner.py`, wrapped by `virt-clone`
//! (ticket 16).
//!
//! [`Cloner`] is the full port: source VM by name or XML, auto clone
//! name and disk paths, the clone/share/preserve choice per disk
//! (`_CloneDiskInfo`), `--force-copy`/`--skip-copy`, nvram, serial file
//! paths, MAC/UUID collision checks, `--replace`, and the real storage
//! duplication (`createXMLFrom` for managed volumes, a sparse local copy
//! otherwise — see `diskbackend.rs`). It edits the new VM's XML on the
//! `edit_xml` DOM, so everything it doesn't touch survives as-is.

use uuid::Uuid;
use virtinst_xml::{parse_libvirt_xml, Document, Element};

/// libvirt's own MAC-address OUI convention (`devices/interface.py`'s
/// `_random_mac`): QEMU/KVM domains get `52:54:00`, Xen gets `00:16:3E`.
/// The remaining three bytes are random — upstream's docstring claims
/// the first bit of the first random byte is masked to 0, but the
/// actual code doesn't do that; checked directly, not assumed.
const OUI_QEMU: [u8; 3] = [0x52, 0x54, 0x00];
const OUI_OTHER: [u8; 3] = [0x00, 0x16, 0x3E];

/// Upstream's `fake_conn_predictable()` gate (`connection.py`'s
/// `_fake_conn_predictable`, set from `MagicURI`'s `,predictable` flag)
/// — checked via an env var here rather than threaded from a
/// `Connection`/URI, since `MagicURI` itself was never ported (see
/// `connection::uri`'s doc comment for why: "upstream's own test-suite
/// fake-connection harness ... not a user-facing feature"). An env var
/// fits without reopening that call: ticket 19's golden-fixture harness
/// spawns each CLI binary as its own OS process (unlike upstream's
/// single shared pytest process running every `Command` in-process),
/// so there's never a need for predictable and non-predictable
/// generation in the same process — a real invocation never sets this,
/// a harness invocation always does, one gate per process is enough.
fn test_predictable() -> bool {
    std::env::var_os("VIRTINST_TEST_PREDICTABLE").is_some()
}

/// A fresh domain UUID — upstream's `Guest.generate_uuid(conn)`, minus
/// the `conn`-collision check (nothing here queries an existing
/// connection for name/UUID clashes yet, same gap `generate_mac`'s own
/// doc comment already notes for MAC collisions). Centralizes what was
/// 7 separate inline `Uuid::new_v4().to_string()` call sites across
/// `cloner.rs` and every `install/*.rs` builder — pure dedup, and now
/// also [`test_predictable`]'s one hook point for UUIDs, same as
/// `generate_mac` is for MACs. The fixed constant matches upstream's
/// own testing hack exactly (`guest.py`'s `_randomUUID`).
pub fn generate_uuid() -> String {
    if test_predictable() {
        return "00000000-1111-2222-3333-444444444444".to_string();
    }
    Uuid::new_v4().to_string()
}

/// Shared state for [`testsuite_mac`]'s counter — see its own doc
/// comment.
static MAC_COUNTER: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(0);

/// Upstream's `_testsuite_mac()` (`devices/interface.py`) — a fixed MAC
/// that stays the same across every call in one process *unless*
/// `VIRTINST_TEST_SUITE_INCREMENT_MACADDR` is set, in which case each
/// call increments the last digit. Two distinct behaviors from one env
/// var, both real: most fixtures want every generated MAC in one
/// invocation to read identically (proves accidental double-generation
/// where one shared value was intended, invisible if MACs always
/// differed); a few need genuinely distinct MACs per device and opt in
/// with the second var. Ported byte-for-byte including the quirk this
/// implies: past a count of 4 the appended digit exceeds 9 and the MAC
/// stops looking like a real one (`"00:11:22:33:44:510"`) — upstream's
/// own behavior, not something to "fix" here since fixture data was
/// generated by this exact function.
fn testsuite_mac() -> String {
    use std::sync::atomic::Ordering;

    let counter = MAC_COUNTER.load(Ordering::SeqCst);
    // Upstream's `base[:-1] + str(int(base[-1]) + counter)`: only the
    // very last character of "00:11:22:33:44:55" is dropped and
    // recomputed — the second "5" is `base[:-1]`'s own trailing
    // character, not part of the appended digit. Missing it here would
    // produce "...:44:5" instead of "...:44:55" at counter=0.
    let ret = format!("00:11:22:33:44:5{}", 5 + counter);
    let next = if std::env::var_os("VIRTINST_TEST_SUITE_INCREMENT_MACADDR").is_some() {
        counter + 1
    } else {
        0
    };
    MAC_COUNTER.store(next, Ordering::SeqCst);
    ret
}

/// A random MAC in libvirt's own format — upstream's
/// `DeviceInterface.generate_mac`, minus the connection-collision retry
/// loop (see this module's doc comment for why).
pub fn generate_mac(is_qemu: bool) -> String {
    if test_predictable() {
        return testsuite_mac();
    }
    let oui = if is_qemu { OUI_QEMU } else { OUI_OTHER };
    // Harvest 3 random bytes from a UUIDv4's own randomness rather than
    // adding a `getrandom` dependency for one 3-byte draw — `uuid`'s
    // `v4` feature already pulls it in internally. Bytes 0-2 of a v4
    // UUID are untouched by the version/variant bit-twiddling (that
    // lands on bytes 6 and 8), so they're as random as any other byte
    // in it.
    let r = Uuid::new_v4();
    let b = r.as_bytes();
    format!(
        "{:02x}:{:02x}:{:02x}:{:02x}:{:02x}:{:02x}",
        oui[0], oui[1], oui[2], b[0], b[1], b[2]
    )
}

/// Guards every test that either flips [`test_predictable`]'s env var or
/// asserts a *real* (non-predictable) generated UUID/MAC's shape — both
/// `VIRTINST_TEST_PREDICTABLE`/`VIRTINST_TEST_SUITE_INCREMENT_MACADDR`
/// and the values [`generate_uuid`]/[`generate_mac`] return are
/// process-global state, and `cargo test`'s default parallelism runs
/// `#[test]` fns on separate threads within *one* process — the same
/// hazard `virtinst-cli`'s `TEST_DOMAIN_LOCK` exists for, applied here
/// to environment variables instead of a shared `test:///` domain.
/// `pub(crate)` so `install/*.rs`'s own OUI-prefix assertions (which
/// this predictable-mode leaking into would also break) can join it.
#[cfg(test)]
pub(crate) static PREDICTABLE_TEST_LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());

/// Sets `<tag>value</tag>` directly under `root`, creating the element
/// if it wasn't already there — `<name>`/`<uuid>` always exist on a
/// real domain document, but this stays honest about not assuming it.
fn set_text(doc: &mut Document, root: Element, tag: &str, value: &str) {
    match root.find(doc, tag) {
        Some(el) => el.set_text_content(doc, value),
        None => {
            let el = Element::new_with_text(doc, tag, value);
            root.push_child(doc, el)
                .expect("a freshly-created detached element always attaches cleanly");
        }
    }
}

