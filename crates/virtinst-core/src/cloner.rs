    /// instance per process, and `Cloner` creates pools on it
    /// (`manage_path`), so tests on it would see each other's pools.
    fn private_test_conn(name: &str) -> Connection {
        let path =
            std::env::temp_dir().join(format!("virtinst-cloner-{name}-{}.xml", std::process::id()));
        std::fs::write(&path, "<node/>").unwrap();
        let conn = Connection::open(&format!("test://{}", path.display()))
            .expect("test:/// driver always opens");
        let _ = std::fs::remove_file(&path);
        conn
    }

    /// A MAC only in a running VM's live XML (not in its persistent
    /// config any more) is still "in use", like upstream's
    /// `check_mac_in_use` over `XMLDesc(0)`.
    #[test]
    fn mac_in_use_sees_a_running_vms_live_xml() {
        let conn = private_test_conn("live-mac");
        let xml = |devices: &str| {
            format!(
                "<domain type='test'><name>live</name>\
                 <uuid>12345678-1234-1234-1234-123456789abc</uuid><memory>8192</memory>\
                 <os><type>hvm</type></os><devices>{devices}</devices></domain>"
            )
        };
        let dom = VirtDomain::define_xml(
            conn.as_connect(),
            &xml("<interface type='user'><mac address='52:54:00:aa:bb:cc'/></interface>"),
        )
        .unwrap();
        dom.create().unwrap();
        // Drop the NIC from the persistent config only: the running VM
        // still has it.
        VirtDomain::define_xml(conn.as_connect(), &xml("")).unwrap();
        let err = check_mac_in_use(&conn, "52:54:00:AA:BB:CC").unwrap_err();
        assert_eq!(
            err,
            "The MAC address '52:54:00:AA:BB:CC' is in use by another virtual machine."
        );
        assert!(check_mac_in_use(&conn, "52:54:00:aa:bb:cd").is_ok());
    }

    /// `_init_new_guest` plus `prepare` on `--original-xml` input:
    /// every unique host side value changes, nothing else does.
    #[test]
    fn rewrites_the_unique_host_side_config() {
        let conn = private_test_conn("rewrite");
        let mut cloner = Cloner::new(&conn, None, Some(SOURCE_FIXTURE)).unwrap();
        // The disk doesn't exist, so leave it shared (--skip-copy).
        cloner.diskinfos_mut()[0].set_share_requested();
        cloner.prepare().unwrap();
        assert_eq!(cloner.src_name(), "original");
        assert_eq!(cloner.new_name(), "original-clone");

        let doc = parse_libvirt_xml(&cloner.new_xml()).unwrap();
        let root = doc.root_element().unwrap();
        let text = |path: &[&str]| {
            virtinst_xml::resolve_path(&doc, root, path).map(|e| e.text_content(&doc))
        };
        let attr = |path: &[&str], name: &str| {
            virtinst_xml::resolve_path(&doc, root, path)
                .and_then(|e| e.attribute(&doc, name))
                .map(str::to_string)
        };
        assert_eq!(root.attribute(&doc, "id"), None);
        assert_eq!(text(&["title"]), None);
        let uuid = text(&["uuid"]).unwrap();
        assert_ne!(uuid, "11111111-1111-1111-1111-111111111111");
        assert_eq!(text(&["sysinfo", "system", "entry"]), Some(uuid));
        let mac = attr(&["devices", "interface", "mac"], "address").unwrap();
        assert_ne!(mac, "52:54:00:aa:bb:cc");
        assert_eq!(attr(&["devices", "interface", "target"], "dev"), None);
        assert_eq!(
            attr(&["devices", "graphics"], "port").as_deref(),
            Some("-1")
        );
        assert_eq!(attr(&["devices", "graphics"], "autoport"), None);
        assert_eq!(attr(&["devices", "channel", "source"], "path"), None);
        assert_eq!(
            attr(&["devices", "disk", "source"], "file").as_deref(),
            Some("/nonexistent/original.qcow2")
        );
        assert_eq!(root.find_all(&doc, "commandline").len(), 1);
        // Attribute order is the source's.
        assert!(cloner
            .new_xml()
            .contains(r#"<target dev="vda" bus="virtio"/>"#));
    }

